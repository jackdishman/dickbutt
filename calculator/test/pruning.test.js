test('rehashing cannot conceal forged pruning cursors, removals or retained state',async t=>{
 for(const fault of ['cursor-type','cursor-overflow','cursor-forged','missing-summary','duplicate','retained-drop','settlement-block']) {
  const f=await historyFixture(t,{pruneSettledPlans:true});await f.advance();await f.advance();
  rewriteHistory(f.dir,rows=>{
   const record=rows[2].record;
   if(fault==='cursor-type')record.state.highestPrunedRoundId=1;
   if(fault==='cursor-overflow')record.state.highestPrunedRoundId=(1n<<256n).toString();
   if(fault==='cursor-forged')record.state.highestPrunedRoundId='99';
   if(fault==='missing-summary')record.prunedRounds=[];
   if(fault==='duplicate')record.prunedRounds.push({...record.prunedRounds[0]});
   if(fault==='retained-drop')record.state.plans={};
   if(fault==='settlement-block')record.prunedRounds[0].settledAt--;
  });
  assert.throws(()=>new Journal(f.dir).entries(),/uint256|removals|prior retained|retained plans|settlement identity/,fault);
 }
});

