function rewriteHistory(dir,mutate) {
 const rows=new Journal(dir).entries();mutate(rows);let previous=null;
 for(const [index,row]of rows.entries()) {
  row.previous=previous;row.hash=hash({previous,record:row.record});previous=row.hash;
  fs.writeFileSync(path.join(dir,'periods',`${String(index+1).padStart(8,'0')}.json`),stringify(row));
 }
}
const root='0x'+'12'.repeat(32);
const samplePlan={roundId:'1',root,total:'10',payouts:{[holderA]:'10'},toBlock:90};
const sampleState=()=>({highestPrunedRoundId:'0',accrued:{},plans:{1:structuredClone(samplePlan)}});
const options={pruneSettledPlans:true};

