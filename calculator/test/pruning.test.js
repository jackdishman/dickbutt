test('pruning deletes only freshly reconciled paid, partially paid, cancelled or superseded plans',async()=>{
 for(const kind of ['paid','partial','cancelled','foreign']) {
  const state=sampleState();
  if(kind==='partial'){state.plans[1].total='15';state.plans[1].payouts[holderB]='5';}
  const foreign='0x'+'f0'.repeat(32),distributed=kind==='paid'||kind==='partial'?10n:0n;
  const distributor={roundInfo:async(_id,{blockTag})=>{assert.equal(blockTag,100);return [kind==='foreign'?foreign:root,BigInt(state.plans[1].total),distributed,false,true];},
   filters:{Paid:()=>1},queryFilter:async()=>distributed?[{blockNumber:99,args:{account:holderA,amount:10n}}]:[]};
  const result=await reconcile(distributor,state,100,2000,options);
  assert.deepEqual(state.plans,{});assert.equal(state.highestPrunedRoundId,'1');
  assert.deepEqual(result.prunedRounds,[{roundId:'1',root,settledAt:100,superseded:kind==='foreign',...(kind==='foreign'?{foreignRoot:foreign}:{})}]);
  assert.deepEqual(state.accrued,kind==='partial'?{[holderB]:5n}:kind==='paid'?{}:{[holderA]:10n});
  const before=structuredClone(state);
  await reconcile({roundInfo:async()=>{throw Error('pruned round must not be recredited again');}},state,101,2000,options);
  assert.deepEqual(state,before);
 }
});

